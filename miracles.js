function renderCategoryFilters() {
  const toolbar = document.querySelector('.miracle-toolbar');
  if (!toolbar) return;

  const bar = document.createElement('div');
  bar.className = 'miracle-category-bar';
  bar.setAttribute('role', 'group');
  bar.setAttribute('aria-label', 'Filter by category');
  bar.innerHTML = FILTER_DEFS.map(f => `
    <button class="miracle-chip${f.slug === 'all' ? ' is-active' : ''}"
            data-filter="${f.slug}"
            type="button">${f.label}</button>
  `).join('');

  // Insert before the country-jump nav
  const jumpNav = toolbar.querySelector('.country-jump');
  toolbar.insertBefore(bar, jumpNav);

  bar.addEventListener('click', e => {
    const chip = e.target.closest('.miracle-chip');
    if (!chip) return;
    bar.querySelectorAll('.miracle-chip').forEach(c => c.classList.remove('is-active'));
    chip.classList.add('is-active');
    applyFilters();
  });
}

/* ------------------------------------------------------------------
   SEARCH + FILTER  (combined)
   ------------------------------------------------------------------ */
function applyFilters() {
  const input  = document.getElementById('miracle-search');
  const empty  = document.getElementById('miracle-empty');
  const active = document.querySelector('.miracle-chip.is-active');
  const cat    = active ? active.dataset.filter : 'all';
  const q      = input ? input.value.trim().toLowerCase() : '';
  let anyVisible = false;

  document.querySelectorAll('.country-section').forEach(section => {
    let sectionVisible = false;
    section.querySelectorAll('.miracle-card').forEach(card => {
      const matchCat   = cat === 'all' || card.dataset.category === cat;
      const matchQuery = !q || card.dataset.search.includes(q);
      const show = matchCat && matchQuery;
      card.style.display = show ? '' : 'none';
      if (show) sectionVisible = true;
    });
    section.style.display = sectionVisible ? '' : 'none';
    if (sectionVisible) anyVisible = true;
  });

  if (empty) empty.style.display = anyVisible ? 'none' : 'block';
}

function initSearch() {
  const input = document.getElementById('miracle-search');
  if (!input) return;
  input.addEventListener('input', applyFilters);
}

