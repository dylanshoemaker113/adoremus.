function renderMiracles(data) {
  const root = document.getElementById('miracle-list');
  if (!root) return;
  root.innerHTML = data.map(country => `
    <section class="country-section" id="${slugify(country.country)}">
      <div class="country-heading">
        <h2>${country.country}</h2>
        <span class="country-count">${country.entries.length} miracle${country.entries.length !== 1 ? 's' : ''}</span>
      </div>
      <div class="miracle-grid">
        ${country.entries.map(e => cardHTML(country.country, e)).join('')}
      </div>
    </section>
  `).join('');
}

